	);

	if ( $existing ) {
		$post_data['ID'] = $existing->ID;
		$post_id = wp_update_post( $post_data );
		echo "Updated article: {$item['title']} (ID {$post_id})\n";
	} else {
		$post_id = wp_insert_post( $post_data );
		echo "Created article: {$item['title']} (ID {$post_id})\n";
	}

	if ( $post_id && ! is_wp_error( $post_id ) ) {
		set_post_thumbnail( $post_id, $item['thumbnail'] );
	}
}

